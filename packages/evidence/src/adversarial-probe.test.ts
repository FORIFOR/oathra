function run(contract: CallContract, mode: ConfirmationMode | undefined, lines: Line[]) {
  const engine = new EvidenceEngine({ language: "ja", now: NOW, ...(mode ? { confirmation: mode } : {}) });
  lines.forEach(([who, text], i) => engine.ingest({ id: `u${i}`, source: who === "A" ? "caller" : "callee", text: text.normalize("NFKC"), t: i }));
  return evaluate(contract, engine, "completed");
}
